#!/bin/sh
# Apply the Unity single-instance fix to a game directory.
# Usage: ./apply.sh /path/to/game/directory
#
# This will:
#   1. Copy the correct library (32-bit or 64-bit) into the game dir
#   2. Create or patch the launch script to LD_PRELOAD the fix
#
# Detects whether the game is 32-bit or 64-bit automatically.

set -e

if [ $# -lt 1 ]; then
    echo "Usage: $0 /path/to/game/directory"
    echo ""
    echo "Fixes old Unity 4.x games that fail with 'Player is already running'"
    echo "when Electron/CEF processes are present on the system."
    echo ""
    echo "Examples:"
    echo "  $0 ~/Games/shadowrun-returns/game"
    echo "  $0 ~/.steam/steam/steamapps/common/Infinifactory"
    exit 1
fi

GAME_DIR="$(cd "$1" 2>/dev/null && pwd)"
if [ ! -d "$GAME_DIR" ]; then
    echo "Error: '$1' is not a valid directory"
    exit 1
fi

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

echo "== Unity Single-Instance Fix Applicator =="
echo "  Game dir: $GAME_DIR"
echo ""

# Find the main executable
EXE=""
for candidate in "$GAME_DIR"/*.x86_64 "$GAME_DIR"/*.x86 "$GAME_DIR"/Shadowrun "$GAME_DIR"/ShadowrunEditor; do
    if [ -f "$candidate" ] && [ -x "$candidate" ]; then
        EXE="$candidate"
        break
    fi
done

# Fallback: first executable in the dir that looks like a game binary
if [ -z "$EXE" ]; then
    for f in "$GAME_DIR"/*; do
        if [ -f "$f" ] && [ -x "$f" ] && ! echo "$f" | grep -qiE "\.(sh|so|py|rb)$"; then
            file "$f" 2>/dev/null | grep -q "ELF" || continue
            EXE="$f"
            break
        fi
    done
fi

if [ -z "$EXE" ]; then
    echo "Error: could not find a game executable in '$GAME_DIR'"
    exit 1
fi

echo "  Executable: $EXE"
BITS=$(file "$EXE" | grep -oP '\d{2}-bit' | head -1)
echo "  Architecture: $BITS"
echo ""

# Determine which library to use
ARCH=""
SUFFIX=""
case "$BITS" in
    32-bit) ARCH=32; SUFFIX=32 ;;
    64-bit) ARCH=64; SUFFIX=64 ;;
    *)
        echo "Error: unknown architecture in '$EXE'"
        exit 1
        ;;
esac

LIB_NAME="unity-fix-${SUFFIX}.so"
LIB_SRC="${SCRIPT_DIR}/${LIB_NAME}"
LIB_DST="${GAME_DIR}/${LIB_NAME}"

if [ ! -f "$LIB_SRC" ]; then
    echo "Error: required library not found: $LIB_SRC"
    echo "Run ./build.sh first to build the libraries."
    exit 1
fi

echo "== Installing fix library =="
cp -v "$LIB_SRC" "$LIB_DST"
echo ""

# Look for existing launch scripts
WRAPPER=""
for script in "$GAME_DIR"/*.sh "$GAME_DIR"/start.sh "$GAME_DIR"/launch.sh; do
    if [ -f "$script" ] && [ -x "$script" ]; then
        WRAPPER="$script"
        echo "  Found launch script: $WRAPPER"
    fi
done

# Patch the most appropriate wrapper, or create a new one
PATCHED=0
if [ -n "$WRAPPER" ]; then
    for f in "$WRAPPER"; do
        if grep -q "./\$\|./\$SRR\|./\$GAME\|\./\$" "$f" 2>/dev/null; then
            echo "== Patching launch script: $f =="
            # Insert LD_PRELOAD before the first ./executable line
            TMP=$(mktemp)
            awk -v lib="$LIB_NAME" -v dir="$GAME_DIR" '
                /^\.\// && !done {
                    print "# Unity single-instance fix"
                    print "export LD_PRELOAD=\""dir"/"lib":${LD_PRELOAD}\""
                    print ""
                    done=1
                }
                { print }
            ' "$f" > "$TMP" && mv "$TMP" "$f"
            chmod +x "$f"
            PATCHED=1
            echo "  Patched: $f"
            break
        fi
    done
fi

if [ "$PATCHED" -eq 0 ]; then
    echo "== Creating wrapper script =="
    cat > "${GAME_DIR}/unity-fix-launch.sh" << WRAPEOF
#!/bin/sh
# Unity single-instance fix wrapper (generated by apply.sh)
# See: https://github.com/ValveSoftware/steam-for-linux/issues/12159

export LD_PRELOAD="${GAME_DIR}/${LIB_NAME}:\${LD_PRELOAD}"

# Try common executable names
for exe in "$GAME_DIR"/*.x86_64 "$GAME_DIR"/*.x86 "$GAME_DIR"/Shadowrun "$GAME_DIR"/ShadowrunEditor; do
    if [ -x "\$exe" ] && [ -f "\$exe" ]; then
        echo "Launching: \$exe"
        exec "\$exe" "\$@"
    fi
done

echo "Error: could not find game executable"
exit 1
WRAPEOF
    chmod +x "${GAME_DIR}/unity-fix-launch.sh"
    echo "  Created: ${GAME_DIR}/unity-fix-launch.sh"
fi

echo ""
echo "== Done =="
echo ""
echo "Next steps:"
echo "  - Run the game using the patched launcher script"
echo "  - If using Steam: set launch options to:"
echo "      LD_PRELOAD=\"${LIB_DST}:\\${LD_PRELOAD}\" %command%"
echo ""
echo "  - If using GOG: run via the .sh script in the game directory"
